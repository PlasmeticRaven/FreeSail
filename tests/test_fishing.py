"""Fishing (spec M7b §21a; package 56): the grounds as data with their sources, the gear
the smack and the lugger carry and no other, the one catch function at both details, the
well and the hold's salt and the spoilage, the fish quay, the gear's sail allowance and
its drag, the fishermen promoted; and the glass on a near ship by tiers (§21b), with the
sighting's bearing and course. The truths are 7b-105 to 7b-107 (`test_known_truths.py`);
these are the parts."""

