def test_the_gear_is_refused_in_words_where_she_carries_none_or_the_ground_does_not_serve():
    frigate = world_at(ship="data/ships/frigate-36.yaml")
    assert frigate.fishery is None
    e = frigate.submit("shoot the trawl")
    assert e.kind == "order.rejected" and "no fishing gear" in e.text
    lug = world_at(ship=LUGGER)
    e = lug.submit("shoot the seine")
    assert e.kind == "order.rejected" and "carries no seine" in e.text
    w = world_at()
    e = w.submit("shoot the trawl")
    assert e.kind == "order.rejected" and "no ground for the trawl" in e.text
    off = world_at(lat=49.95, lon=-4.70)
    e = off.submit("shoot the seine")
    assert e.kind == "order.rejected" and "no fishing ground" in e.text
    night = world_at(when=datetime(1805, 8, 14, 23, 0))
    e = night.submit("shoot the seine")
    assert e.kind == "order.rejected" and "Not at this hour" in e.text
    winter = world_at(when=datetime(1805, 2, 14, 11, 0))
    e = winter.submit("shoot the seine")
    assert e.kind == "order.rejected" and "in February" in e.text
    e = w.submit("haul the seine")
    assert e.kind == "order.rejected" and "No gear is in the water" in e.text
    e = w.submit("sell the catch")
    assert e.kind == "order.rejected"


def test_a_sail_beyond_the_gears_allowance_is_refused_while_it_is_out_and_the_trawl_drags():
    w = world_at()
    fishery = w.fishery
    fishery.out = F.GearOut("trawl", "trawl", "the trawl", "eddystone", w.clock.tick)
    F.rig_gear_drag(w, fishery)
    assert w.ship.extra["gear_drag"] == F.TRAWL_DRAG
    e = w.submit("set the topsail")
    assert e.kind == "order.rejected" and "towing her trawl" in e.text
    assert "Haul the trawl first" in e.text
    assert "towing her trawl" in w.readings.value("work_in_hand")["words"]
    fishery.out = None
    F.rig_gear_drag(w, fishery)
    assert "gear_drag" not in w.ship.extra


def test_the_catch_is_sold_at_a_fish_quay_at_its_price_and_the_spoiled_go_over_the_side():
    w = world_at(lat=50.163, lon=-5.0345)  # Carrick Road
    w.submit("let go the best bower")
    w.run(300)
    fishery = w.fishery
    fishery.catch.stow({"pilchards": 2.0, "mackerel": 0.5}, w.clock.tick, w.clock.ship_time)
    next(lot for lot in fishery.catch.lots if lot.fish == "mackerel").spoiled = True
    before = w.purse.pounds
    e = w.submit("sell the catch")
    assert e.kind == "fishing.sold", e.text
    assert w.purse.pounds - before == pytest.approx(2.0 * 6.0)  # Falmouth's factor 1
    assert "thrown over the side" in e.text and not fishery.catch.lots


