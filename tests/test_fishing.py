def test_the_far_fishermans_gear_follows_the_evolutions_times_and_the_one_catch_function():
    w = world_at(ship="data/ships/frigate-36.yaml", lat=49.85, lon=-5.2)
    w.vessels.serial += 1
    v = vessel_from_spec(
        w,
        {
            "description": "smack",
            "name": "Brothers",
            "nation": "britain",
            "position": {"lat_deg": GERRANS[0], "lon_deg": GERRANS[1]},
            "goal": "bound for Falmouth",
            "intent": "fish on the seine ground in Gerrans Bay for 2 hours from Falmouth",
        },
        w.vessels.serial,
    )
    w.vessels.add(v)
    fishery = F.far_fishery(v)
    assert fishery is not None and fishery.carries("seine") is not None
    for _ in range(int(F._shoot_s("seine") // 60) + 1):
        F.far_work(w, v, 60.0)
    assert fishery.out is not None and fishery.out.kind == "seine"
    for _ in range(60):
        F.far_work(w, v, 60.0)
    assert fishery.out.state == "hauling"
    for _ in range(int(F._haul_s("seine") // 60) + 1):
        F.far_work(w, v, 60.0)
    assert fishery.out is None and fishery.catch.tons() > 3.0


