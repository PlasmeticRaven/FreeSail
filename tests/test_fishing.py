# -- the one catch function --------------------------------------------------------------


def test_the_catch_follows_the_ground_the_season_the_hour_and_the_wind():
    w = world_at()
    g = F.find_ground(w, "gerrans-bay")
    aug = datetime(1805, 8, 14, 10, 0)
    feb = datetime(1805, 2, 14, 10, 0)
    day = F.take(g, "seine", aug, "day", 8.0, 3600.0)
    assert day["pilchards"] == pytest.approx(3.0) and day["mackerel"] == pytest.approx(1.0)
    assert F.take(g, "seine", aug, "night", 8.0, 3600.0) == {}  # the seine by day
    assert F.take(g, "seine", feb, "day", 8.0, 3600.0) == {}  # out of season
    assert F.take(g, "seine", aug, "day", 20.0, 3600.0) == {}  # beyond the boats' wind
    half = F.take(g, "seine", aug, "day", 16.0, 3600.0)["pilchards"]
    assert half == pytest.approx(1.5)  # half at the most wind
    mounts = F.find_ground(w, "mounts-bay")
    night = F.take(mounts, "drift nets", aug, "night", 8.0, 3600.0)["pilchards"]
    dusk = F.take(mounts, "drift nets", aug, "twilight", 8.0, 3600.0)["pilchards"]
    assert dusk == pytest.approx(1.5 * night)  # the change of light (Holdsworth pp. 98-99)
    eddy = F.find_ground(w, "eddystone")
    assert F.take(eddy, "trawl", aug, "day", 10.0, 3600.0, way_kn=6.0) == {}
    assert F.take(eddy, "trawl", aug, "day", 10.0, 3600.0, way_kn=2.5)


def test_the_haul_fills_the_well_then_the_hold_salted_while_the_salt_lasts():
    w = world_at()
    fishery = w.fishery
    assert fishery.catch.well_tons == pytest.approx(3.0)  # 9.1 m3 at a third of a ton
    w.hold.goods["salt"] = 0.2
    fishery.out = F.GearOut("seine", "seine", "the seine", "gerrans-bay", w.clock.tick)
    fishery.out.taken = {"pilchards": 4.5}
    text, data = F.haul_into(w, fishery)
    wells = [lot for lot in fishery.catch.lots if lot.where == "well"]
    salted = [lot for lot in fishery.catch.lots if lot.salted]
    green = [lot for lot in fishery.catch.lots if lot.where == "hold" and not lot.salted]
    assert sum(lot.tons for lot in wells) == pytest.approx(3.0)
    assert sum(lot.tons for lot in salted) == pytest.approx(0.2 / 0.33, rel=1e-3)
    assert green and green[0].spoils_tick == w.clock.tick + 12 * 3600  # summer, twelve hours
    assert "salt" not in w.hold.goods  # the salt used, broken out of the manifest
    assert "Struck down" in text and data["tons"] == pytest.approx(4.5)
    assert not wells[0].alive  # a pilchard does not live in the well (Steel 1805, WELL)


def test_the_spoilage_is_said_when_a_lot_turns_and_once_a_day_and_salt_keeps():
    w = world_at(when=datetime(1805, 8, 14, 7, 0))
    fishery = w.fishery
    fishery.catch.stow({"pilchards": 3.5}, w.clock.tick, w.clock.ship_time, salt=None)
    w.run(3600 + 60)  # past eight in the morning
    days = [e for e in w.log.since(0) if e.kind == "fishing.catch"]
    assert len(days) == 1 and "pilchards in the well" in days[0].text
    w.run(12 * 3600)
    spoiled = [e for e in w.log.since(0) if e.kind == "fishing.spoiled"]
    assert spoiled and "farmers' dung" in spoiled[0].text
    assert any(lot.spoiled and lot.where == "hold" for lot in fishery.catch.lots)


