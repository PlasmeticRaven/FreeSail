SMACK = "data/ships/smack.yaml"
LUGGER = "data/ships/lugger.yaml"
GERRANS = (50.195, -4.945)  # the seine ground in Gerrans Bay (data/fishing/channel-west.yaml)


def world_at(
    ship=SMACK, lat=GERRANS[0], lon=GERRANS[1], when=datetime(1805, 8, 14, 9, 0), wind=10.0
):
    sc = Scenario(
        start_time=when,
        wind_from_deg=270.0,
        wind_speed_kn=wind,
        gustiness=0.0,
        variability=0.0,
        position={"lat_deg": lat, "lon_deg": lon},
        region="channel-west",
        ports=["falmouth", "plymouth", "brest"],
        nation="britain",
    )
    return make_world(7, ship, sc)


# -- the data -------------------------------------------------------------------------------


def test_every_ground_fish_and_yield_carries_its_source_and_names_known_fish_and_gear():
    data = F.load_fishing()
    fish = data["fish"]
    gear = data["gear"]
    for name, spec in fish.items():
        assert spec.get("source"), name
        assert set(spec["keeps_hours"]) == {"summer", "winter"}
        assert spec["price"]["fresh"] > 0 and spec["price"]["salted"] > 0
        assert spec.get("well_days" if spec["well"] else "well_hours"), name
    for kind, spec in gear.items():
        assert kind in F.EVOLUTIONS and spec.get("source") and spec["hours_a_shot"] > 0
    assert data["regions"], "no region's grounds"
    for grounds in data["regions"].values():
        for g in grounds:
            assert g.get("source") and (g.get("feature") or g.get("position")), g["id"]
            for e in g["fish"]:
                assert e["fish"] in fish and e["gear"] in gear, (g["id"], e)
                assert e.get("source"), (g["id"], e)
                assert (
                    "judgement" in e["source"]
                    or "Holdsworth" in e["source"]
                    or ("EB 1810" in e["source"])
                ), (g["id"], e)


def test_the_grounds_are_keyed_to_the_charts_features_and_the_business_grounds_are_named():
    w = world_at()
    ids = {g.id for g in F.grounds(w)}
    assert {"gerrans-bay", "mounts-bay", "eddystone", "poll-bank", "iroise"} <= ids
    eddy = F.find_ground(w, "the oozy ground off the Eddystone")
    assert eddy is not None and eddy.feature == "eddystone-oozy-ground"
    assert F.find_ground(w, "the seine ground in Gerrans Bay").id == "gerrans-bay"
    # a ground pricked at a position lies at sea, in the depth the gear wants
    for g in F.grounds(w):
        depth = w.chart.depth_at(g.position)
        assert depth is not None and depth > 5.0, g.id
    # a bottom the tables do not name keeps the default, with a yield
    f = w.chart.feature("soundings-off-ushant")
    d = F.default_ground(f)
    assert not d.named and d.in_season("trawl", 6)


