def test_a_made_out_line_gives_her_bearing_and_the_course_she_stands():
    w = world_at(ship="data/ships/frigate-36.yaml", lat=49.9, lon=-5.0)
    w.vessels.serial += 1
    v = vessel_from_spec(
        w,
        {
            "description": "merchant brig",
            "name": "Nancy",
            "nation": "britain",
            "position": {"lat_deg": 49.93, "lon_deg": -5.0},
            "goal": "bound for 49 55 N 4 30 W",
        },
        w.vessels.serial,
    )
    w.vessels.add(v)
    w.run(180)
    made = [e for e in w.log.since(0) if e.kind == "lookout.made_out"]
    sighted = [e for e in w.log.since(0) if e.kind == "lookout.sighting" and "Sail ho" in e.text]
    assert sighted
    reading = w.readings.value("sail_in_sight")
    assert "standing to the" in reading["words"] and "bearing" in reading["words"]
    for e in made:
        assert ", bearing " in e.text, e.text
    glass = [e for e in w.log.since(0) if e.kind == "lookout.glass"]
    assert glass and "under way on the" in glass[0].text
    e = w.submit("the glass on the brig")
    assert e.kind == "lookout.glass" and "under way on the" in e.text, e.text
    assert math.isfinite(v.heading_deg)


